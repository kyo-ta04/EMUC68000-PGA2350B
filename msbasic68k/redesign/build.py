# ZPBASE per HW variant: the EXT1 image outgrows the faithful
# 16 KB code budget by 131 bytes, so the EXT HW layout moves
# its zero page up by $400 (see parts/10-config-hw-x.asm).
HW_ZPBASES = {"hw": 0x34000, "ext-hw": 0x34400,
              "hw-c": 0x34000, "ext-hw-c": 0x34400}


def bsd_sum(data: bytes) -> int:
    """The project's BSD sum: rotate the 16-bit sum right by 1
    per byte (LSB wraps to bit15), add the byte, mask to 16 bits.
    (Same definition as proto/tapedeck.py's bsd_sum.)"""
    s = 0
    for b in data:
        s = ((s >> 1) | ((s & 1) << 15)) & 0xFFFF
        s = (s + b) & 0xFFFF
    return s


def make_loader(data: bytes) -> str:
    """DATA-embed loader .bas in the build_puncher_v3.py pattern:
    POKE the binary to $30000, verify byte by byte against the
    DATA, fold the BSD sum over the loaded bytes, and stop --
    CALL $30000 is typed by hand afterwards.  (Ported verbatim
    from the M5f build_hw.py.)"""
    lines = []
    lines.append("10 REM ===== MS-BASIC 68K HW IMAGE LOADER =====")
    lines.append("20 REM POKE THE IMAGE TO $30000 AND VERIFY IT.")
    lines.append("30 REM BEFORE RUN (EVERY COLD START):")
    lines.append("40 REM   LOKE $844A,$30000")
    lines.append("50 REM   CLEAR")
    lines.append(f"60 REM IMAGE: {len(data)} BYTES, "
                 f"BSD SUM {bsd_sum(data)}")
    lines.append("70 REM AFTER 'LOAD OK':  CALL $30000")
    lines.append("80 REM MS-BASIC NEVER RETURNS. EXIT = RESET.")
    lines.append("100 READ NB")
    lines.append("110 FOR I=0 TO NB-1")
    lines.append("120 READ B")
    lines.append("130 POKE $30000+I,B")
    lines.append("140 NEXT")
    lines.append("150 REM --- VERIFY BYTES + BSD SUM ---")
    lines.append("160 RESTORE")
    lines.append("170 READ NB")
    lines.append("180 F=0: S=0")
    lines.append("190 FOR I=0 TO NB-1")
    lines.append("200 READ B")
    lines.append("210 V=PEEK($30000+I)")
    lines.append("220 S=INT(S/2)+32768*(S AND 1): S=S+V: "
                 "IF S>65535 THEN S=S-65536")
    lines.append('230 IF V<>B THEN F=F+1: '
                 'PRINT "MISMATCH AT +";I')
    lines.append("240 NEXT")
    lines.append(f'250 IF F=0 AND S={bsd_sum(data)} THEN '
                 f'PRINT "LOAD OK - {len(data)} BYTES AT $30000, '
                 f'SUM {bsd_sum(data)}": END')
    lines.append('260 PRINT "LOAD FAIL: ";F;" MISMATCHES, SUM=";S')
    lines.append(f"1000 DATA {len(data)}")
    ln = 1010
    for off in range(0, len(data), 16):
        chunk = ",".join(str(b) for b in data[off:off + 16])
        lines.append(f"{ln} DATA {chunk}")
        ln += 10
    return "\n".join(lines) + "\n"


def top_source(variant: str) -> str:
    """The per-flavour top-level source: the variant banner (a
    comment block) followed by one INCLUDE per part, in
    PART_ORDER.  asm68k-py resolves the paths relative to this
    file, i.e. parts/ below the tree root."""
    chunks = [BANNERS[variant]]
    for name in PART_ORDER[variant]:
        chunks.append(f' INCLUDE "parts/{name}"\n')
    return "".join(chunks)


def build(variant: str) -> bool:
    src_name, bin_name, lst_name, c_name, exp_len, exp_sum, \
        loader_name = TARGETS[variant]
    src = HERE / src_name
    src.write_text(top_source(variant))
    print(f"[{variant}] top source -> {src_name}")

    r = subprocess.run(
        [sys.executable, str(ASM68K), str(src), "--bin",
         str(HERE / bin_name), "--list", str(HERE / lst_name),
         "-o", str(HERE / c_name)],
        capture_output=True, text=True)
    print("asm68k:", (r.stdout + r.stderr).strip())
    if r.returncode != 0:
        print(f"[{variant}] FAIL: assembly error")
        return False

    data = (HERE / bin_name).read_bytes()
    got_sum = bsd_sum(data)
    print(f"[{variant}] image: {len(data)} bytes, BSD sum {got_sum}")
    ok = True

    def require(name, cond, detail):
        nonlocal ok
        print(("PASS" if cond else "FAIL"), "-", name, detail)
        ok = ok and cond

    if exp_len is not None:
        require("size matches the reference image",
                len(data) == exp_len, f"{len(data)} == {exp_len}")
        require("BSD sum matches the reference image",
                got_sum == exp_sum, f"{got_sum} == {exp_sum}")

    if variant in HW_ZPBASES:
        zpbase = HW_ZPBASES[variant]
        code_end = HW_ORG + len(data)
        print(f"[{variant}] image ${HW_ORG:05X}-${code_end - 1:05X}")
        require("code fits below ZPBASE",
                code_end <= zpbase,
                f"code end ${code_end:05X} <= ${zpbase:05X} "
                f"(headroom {zpbase - code_end} bytes)")
        require("ZP fits below FNTABV",
                zpbase + HW_ZPSIZE <= HW_FNTABV,
                f"${zpbase + HW_ZPSIZE:05X} <= ${HW_FNTABV:05X}")
        require("FN table fits below TXTTABV",
                HW_FNTABV + HW_FNTAB_SIZE <= HW_TXTTABV,
                f"${HW_FNTABV + HW_FNTAB_SIZE:05X} "
                f"<= ${HW_TXTTABV:05X}")
        require("everything inside the zone",
                HW_ORG >= 0x30000 and HW_MEMSIZV < HW_ZONE_END
                and HW_STACKTOP <= HW_ZONE_END,
                f"zone $30000-${HW_ZONE_END - 1:05X}")
        require("all bases even",
                all(v % 2 == 0 for v in
                    (HW_ORG, zpbase, HW_FNTABV, HW_TXTTABV,
                     HW_MEMSIZV, HW_STACKTOP)),
                "68K word/long alignment")
        print(f"BYTES FREE = {HW_MEMSIZV - HW_TXTTABV} "
              f"(MEMSIZ ${HW_MEMSIZV:05X} - TXTTAB ${HW_TXTTABV:05X})")
        loader = HERE / loader_name
        loader.write_text(make_loader(data))
        print(f"[{variant}] loader -> {loader.name} "
              f"({loader.stat().st_size} bytes of BASIC)")
    else:
        code_end = len(data)
        require("code fits below ZPBASE",
                code_end <= SIM_ZPBASE,
                f"code end ${code_end:05X} <= ${SIM_ZPBASE:05X} "
                f"(headroom {SIM_ZPBASE - code_end} bytes)")

    print(f"[{variant}] build:", "PASS" if ok else "FAIL")
    return ok


def main() -> int:
    args = sys.argv[1:]
    if not args:
        variants = ["sim", "hw", "ext-sim", "ext-hw",
                    "sim-c", "hw-c", "ext-sim-c", "ext-hw-c"]
    elif len(args) == 1 and args[0] in TARGETS:
        variants = [args[0]]
    else:
        print("usage: build.py [sim|hw|rd|rdhw|ext-sim|ext-hw|"
              "sim-c|hw-c|ext-sim-c|ext-hw-c]")
        return 2
    ok = all([build(v) for v in variants])
    print("build:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
