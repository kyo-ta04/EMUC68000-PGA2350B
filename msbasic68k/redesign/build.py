#!/usr/bin/env python3
"""Unified build for the MS-BASIC 68K port (M6 factoring).

The source lives in parts/ as separate files joined at the
existing section boundaries:

  00-header.asm      file header (variant-neutral)
  10-config-sim.asm  layout comment + address EQUs, SIM variant
  10-config-hw.asm   layout comment + address EQUs, HW variant
  20-equates.asm     ACIA / sizes / virtual-ZP slots / tokens
  30-entry-sim.asm   reset vectors at $0
  30-entry-hw.asm    HWENTRY stub at $30000 (EhBASIC CALL entry)
  40-core-a.asm      interpreter core A (tables, INIT, statements)
  50-machine.asm     machine layer (ACIA primitives, BRKCHK,
                     CRDO/STROUT, PRTDEC/DIV10)
  60-core-b.asm      interpreter core B (M3 FP core onward)

A variant is built by SELECTING its config + entry parts and
generating a top-level source (msbasic68k.asm /
msbasic68k-hw.asm) that INCLUDEs the parts in the order above;
asm68k-py expands the INCLUDEs, resolving the paths relative
to the top file.  The top-level sources are generated files --
edit the parts, not them.  (This replaces the M5f build_hw.py
string-rewrite of a single file; build_hw.py is now a thin
shim that runs this script's HW build for run_hw.py.  Until
2026-11-22 build.py concatenated the parts itself; the move
to INCLUDE top files is a pure build-structure change and the
images are byte-identical, as the pins below confirm.)

Flavours (M7): the core parts are cut at the EXT1 hook points
into small faithful/ext part PAIRS (41-reslst, 43-init,
45-crunch, 47-fetch, 48-excol, 49-if, 4B-print, 61-fevar,
63-feu3); a faithful
build takes the -f member of every pair, an EXT build the -x
member, and only an EXT build includes 70-ext1.asm (the EXT1
code layer) before 99-end.asm.  The faithful flavours are
byte-identical to the pre-EXT images -- that is the regression
gate below (expected size / BSD sum).

Variants:
  sim      faithful $0 image, boots from its own reset vectors.
           -> msbasic68k.bin (15492 bytes, BSD sum 32410)
  hw       faithful $30000 landing-zone image for the
           EMUC68000-PGA2350B, entered with EhBASIC's
           CALL $30000 while EhBASIC runs.
           -> msbasic68k-hw.bin (15500 bytes, BSD sum 17566)
           -> msbasic68k-hw-loader.bas (DATA-embed loader)
  ext-sim  EXT1 $0 image -> msbasic68k-ext.bin
  ext-hw   EXT1 $30000 image -> msbasic68k-hw-ext.bin
           -> msbasic68k-hw-ext-loader.bas
  *-c      the M8 banner variants: the same four builds with
           the two-line banner (a "COPYRIGHT 1977 BY
           MICROSOFT CO." second line; parts/65-banner-c.asm)
           for screenshots.  The faithful banner stays the
           original one-liner (65-banner-o.asm).
           -> msbasic68k-c.bin / msbasic68k-hw-c.bin /
              msbasic68k-ext-c.bin / msbasic68k-hw-ext-c.bin
              (+ hw loaders)

(The faithful sums above are the post-M8 reference values:
M8's READY. fix -- no prompt after a stored line -- changed
the branch targets in MAIN, hence the sums, at unchanged
sizes.  Pre-M8: sim 32584, hw 5542.)

Usage: build.py [variant]  (no argument builds all)
Exit status 0 = built and every gate (size, BSD sum, layout
assertions) holds.
"""
