def _order(config: str, entry: str, ext: bool,
           banner: str = "o") -> list:
    """The part sequence for one variant: the faithful/ext part
    pairs resolve by flavour, 70-ext1.asm is EXT-only, and the
    banner part (65-banner-o = the original one-line banner,
    65-banner-c = the M8 COPYRIGHT variant) resolves by the
    banner selector."""
    sfx = "x" if ext else "f"
    parts = ["00-header.asm", f"10-config-{config}.asm",
             "20-equates.asm", f"30-entry-{entry}.asm",
             "40-core-a.asm", f"41-reslst-{sfx}.asm",
             "42-core-a2.asm", f"43-init-{sfx}.asm",
             "44-core-a3.asm", f"45-crunch-{sfx}.asm",
             "46-core-a4.asm", f"47-fetch-{sfx}.asm",
             "48-core-a5.asm", f"48-excol-{sfx}.asm",
             "48-core-a5b.asm", f"49-if-{sfx}.asm",
             "4A-core-a6.asm", f"4B-print-{sfx}.asm",
             "4C-core-a7.asm", "50-machine.asm",
             "60-core-b.asm", f"61-fevar-{sfx}.asm",
             "62-core-b2.asm", f"63-feu3-{sfx}.asm",
             "64-core-b3.asm", f"65-banner-{banner}.asm",
             "66-core-b4.asm"]
    if ext:
        parts.append("70-ext1.asm")
    parts.append("99-end.asm")
    return parts


