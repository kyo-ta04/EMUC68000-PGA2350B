#!/usr/bin/env python3
"""gen_msbasic68k.py -- generate the MS-BASIC 68K image C arrays for
the EMUC68000-PGA2350B firmware, from $0-layout builds of the port.

The $0 layout is the primary build: the image carries its own reset
vectors at offset 0, so the firmware only has to place it at
memory[0] and reset the CPU.  (The $30000 hw builds remain for the
older route where EhBASIC hosts the image and it is entered via
CALL $30000.)

Triple boot (2026-11-23): the firmware carries TWO MS-BASIC images
next to EhBASIC, so this script is parametrised by array name /
size symbol / output base name:

    # phase1 EXT1 image (boot menu 'M'), array MSBASIC68K:
    python3 gen_msbasic68k.py \
        --bin <msbasic-68k>/phase1/msbasic68k-ext.bin \
        --outdir <firmware root> \
        --expect-size 16536 --expect-sum 25401

    # redesign R2 image (boot menu 'R'), array MSBASIC68K_RD:
    python3 gen_msbasic68k.py \
        --bin <msbasic-68k>/redesign/msbasic68k-rdhw.bin \
        --outdir <firmware root> --outbase msbasic68k_rd \
        --array-name MSBASIC68K_RD \
        --expect-size 19794 --expect-sum 52171

The expected size/sum are the gate: they must be the numbers the
respective build.py / test suites report (phase1 ext-sim:
16,536 bytes / BSD sum 25401, the comma-NEXT-fixed build; redesign
rdhw: 19,794 bytes / BSD sum 52171, build-pinned, byte-identical
to rd).  NOTE: the phase1 array embedded before 2026-11-23 was
16,530 bytes / sum 32550 -- the PRE-comma-NEXT-fix build; always
regenerate from the current ext-sim build.

The output follows the exact style of the firmware's ehbasic.c:
a `const uint8_t NAME[]` array, 16 bytes per line, plus a
`const int <name>_size = sizeof(NAME);` definition.  The reset
vectors quoted in the generated comment are read from the image
itself (bytes 0-7), never hard-coded.

Usage:
    python3 gen_msbasic68k.py [--bin PATH] [--outdir PATH]
        [--outbase NAME] [--array-name NAME] [--size-name NAME]
        [--expect-size N] [--expect-sum N]

--size-name defaults to the array name lowercased + "_size"
(MSBASIC68K -> msbasic68k_size, MSBASIC68K_RD -> msbasic68k_rd_size).
--outbase defaults to "msbasic68k" and names both the generated
files (<outbase>.c / <outbase>.h) and the header the .c includes.

After writing, the script re-reads the generated C file, extracts
the array bytes, and verifies them against the .bin (byte-identical)
and against the expected BSD sum.  Exit status 0 = OK.
"""
import argparse
import re
import sys
from pathlib import Path

EXPECTED_SIZE = 16536
EXPECTED_SUM = 25401
ARRAY_NAME = "MSBASIC68K"
OUTBASE = "msbasic68k"


def bsd_sum(data: bytes) -> int:
    """The project's BSD sum: rotate the 16-bit sum right by 1
    per byte (LSB wraps to bit15), add the byte, mask to 16 bits.
    (Same definition as phase1/build_hw.py's bsd_sum.)"""
    s = 0
    for b in data:
        s = ((s >> 1) | ((s & 1) << 15)) & 0xFFFF
        s = (s + b) & 0xFFFF
    return s


def make_header(array_name: str, size_name: str) -> str:
    return (
        "#include <stdint.h>\n"
        "\n"
        f"extern const uint8_t {array_name}[];\n"
        f"extern const int {size_name};\n"
    )


def make_source(data: bytes, srcname: str, array_name: str,
                size_name: str, outbase: str) -> str:
    ssp = int.from_bytes(data[0:4], "big")
    pc = int.from_bytes(data[4:8], "big")
    lines = []
    lines.append("//")
    lines.append(f"// {outbase}.c - 68000 program image (MS-BASIC 68K)")
    lines.append("//")
    lines.append(f"// Generated by gen_msbasic68k.py from {srcname}")
    lines.append("// (MS-BASIC 68K port, $0-layout build).")
    lines.append("// Do not edit by hand; regenerate instead.")
    lines.append("//")
    lines.append(f'#include "{outbase}.h"  // MS-BASIC 68K program image')
    lines.append("")
    lines.append(f"const uint8_t {array_name}[] = {{")
    lines.append("")
    lines.append("// MS-BASIC 68K for EMUC68000-PGA2350B")
    lines.append("// Load address $00000; the image carries its own reset")
    lines.append(f"// vectors (SSP=${ssp:08X}, PC=${pc:08X} entry).")
    lines.append(f"// {len(data)} bytes, BSD sum {bsd_sum(data)}")
    lines.append("// 0x0000 (image offset = absolute address)")
    for off in range(0, len(data), 16):
        chunk = data[off:off + 16]
        body = "".join(f"0x{b:02x}, " for b in chunk)
        if off + 16 >= len(data):
            body = body[:-2]  # last line: no trailing comma
        lines.append(f"  {body} // {off:02X}")
    lines.append("};")
    lines.append("")
    lines.append(f"const int {size_name} = sizeof({array_name});")
    lines.append("")
    return "\n".join(lines)


def extract_array(c_text: str) -> bytes:
    m = re.search(r"\{(.*?)\};", c_text, re.S)
    if not m:
        raise ValueError("array body not found")
    body = m.group(1)
    # Drop // comments first (they contain text like "0x0000" that is
    # not array data).
    body = "\n".join(line.split("//", 1)[0] for line in body.splitlines())
    return bytes(int(tok, 16) for tok in re.findall(r"0x([0-9a-fA-F]{2})", body))


def main() -> int:
    ap = argparse.ArgumentParser()
    here = Path(__file__).resolve().parent
    ap.add_argument("--bin", default=str(here.parent / "phase1" / "msbasic68k.bin"))
    ap.add_argument("--outdir", default=str(here))
    ap.add_argument("--outbase", default=OUTBASE)
    ap.add_argument("--array-name", default=ARRAY_NAME)
    ap.add_argument("--size-name", default=None,
                    help="default: array name lowercased + '_size'")
    ap.add_argument("--expect-size", type=int, default=EXPECTED_SIZE)
    ap.add_argument("--expect-sum", type=int, default=EXPECTED_SUM)
    args = ap.parse_args()

    size_name = args.size_name or (args.array_name.lower() + "_size")

    data = Path(args.bin).read_bytes()
    print(f"input : {args.bin} ({len(data)} bytes, BSD sum {bsd_sum(data)})")
    if len(data) != args.expect_size:
        print(f"ERROR: expected {args.expect_size} bytes, got {len(data)}", file=sys.stderr)
        return 1
    if bsd_sum(data) != args.expect_sum:
        print(f"ERROR: expected BSD sum {args.expect_sum}, got {bsd_sum(data)}", file=sys.stderr)
        return 1

    outdir = Path(args.outdir)
    h_path = outdir / f"{args.outbase}.h"
    c_path = outdir / f"{args.outbase}.c"
    h_path.write_text(make_header(args.array_name, size_name))
    c_path.write_text(make_source(data, Path(args.bin).name,
                                  args.array_name, size_name,
                                  args.outbase))
    print(f"wrote : {h_path}")
    print(f"wrote : {c_path}")

    # Verify: extract the array back out of the generated C and compare.
    back = extract_array(c_path.read_text())
    if back != data:
        print("ERROR: extracted array differs from the .bin", file=sys.stderr)
        return 1
    if bsd_sum(back) != args.expect_sum:
        print(f"ERROR: extracted BSD sum {bsd_sum(back)} != {args.expect_sum}", file=sys.stderr)
        return 1
    print(f"verify: extracted {len(back)} bytes, byte-identical to .bin, "
          f"BSD sum {bsd_sum(back)} == {args.expect_sum}  OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
